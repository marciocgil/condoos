"""Milestone 6 acceptance: a complete fictitious condominium, from upload to report, timed.

Runs against the docker compose stack (API, worker, Mailpit, PostgreSQL), doing what the
people would do through the same API the screens use:

1. onboarding of "Bosque dos Ipês" (docs/pilot/onboarding-bosque-dos-ipes.json) and its
   30 documents, generated by the corpus generator addressed to this condominium;
2. the analyst uploads the contract, then the other 29 corpus documents and the October
   bank statement (OFX);
3. the worker extracts, matches and evaluates; the analyst corrects the exception queue
   using the corpus ground truth (as a person reading the document would) and resolves
   ambiguous matches;
4. the manager validates the serious findings and closes October;
5. the síndica downloads the report (PDF and XLSX).

Usage: make pilot   (after `make reset && make up`; the condominium can be created once)
Writes docs/pilot/run.md and the downloaded reports in docs/pilot/.
"""

