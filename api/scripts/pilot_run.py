ROOT = Path(__file__).resolve().parents[2]
PILOT = ROOT / "docs" / "pilot"
ONBOARDING = PILOT / "onboarding-bosque-dos-ipes.json"
ANALYST = "elisa.analista@atlantida.example.com"
MANAGER = "diego.gerente@atlantida.example.com"
SINDICA = "helena.sindica@ipes.example.com"
MONTH = "2026-10"
LIMIT_SECONDS = 15 * 60
TOKEN = re.compile(r"token=([\w-]+)")


@dataclass
class Run:
    started: float = field(default_factory=time.monotonic)
    steps: list[tuple[str, float, str]] = field(default_factory=list)
    _last: float = field(default_factory=time.monotonic)

    def step(self, name: str, detail: str = "") -> None:
        now = time.monotonic()
        self.steps.append((name, now - self._last, detail))
        self._last = now
        print(f"[{now - self.started:7.1f}s] {name} {detail}", flush=True)

    @property
    def total(self) -> float:
        return time.monotonic() - self.started


async def login(api: str, mailpit: str, email: str) -> httpx.AsyncClient:
    client = httpx.AsyncClient(base_url=api, timeout=120)
    since = time.time() - 2
    r = await client.post("/auth/magic-link", json={"email": email})
    r.raise_for_status()
    async with httpx.AsyncClient(base_url=mailpit, timeout=10) as mp:
        for _ in range(60):
            msgs = (await mp.get("/api/v1/search", params={"query": f"to:{email}"})).json()
            for m in msgs.get("messages", []):
                created = m["Created"].replace("Z", "+00:00")
                if datetime.fromisoformat(created).timestamp() >= since:
                    body = (await mp.get(f"/api/v1/message/{m['ID']}")).json()["Text"]
                    match = TOKEN.search(body)
                    if match:
                        (
                            await client.post("/auth/verify", json={"token": match.group(1)})
                        ).raise_for_status()
                        return client
            await asyncio.sleep(0.5)
    raise RuntimeError(f"nenhum link de acesso para {email}")


async def onboard(admin_url: str) -> str:
    from app.db.session import sessionmaker_for
    from app.onboarding import OnboardingIn
    from app.onboarding import onboard as do_onboard

    spec = OnboardingIn.model_validate(json.loads(ONBOARDING.read_text(encoding="utf-8")))
    engine = create_async_engine(admin_url)
    try:
        async with sessionmaker_for(engine)() as s, s.begin():
            condo = await do_onboard(s, spec)
            return str(condo.id)
    finally:
        await engine.dispose()


async def wait_idle(admin_url: str, condo_id: str, limit_s: float = 600) -> int:
    """Until no job of the condominium (or global, like enrichment) is queued or running."""
    engine = create_async_engine(admin_url)
    deadline = time.monotonic() + limit_s
    try:
        idle_since = None
        while time.monotonic() < deadline:
            async with engine.connect() as conn:
                busy = await conn.scalar(
                    text(
                        "SELECT count(*) FROM job WHERE status IN ('queued', 'running') "
                        "AND (condominium_id = :c OR condominium_id IS NULL) "
                        "AND job_type NOT IN ('indices.refresh', 'retention.purge')"
                    ),
                    {"c": condo_id},
                )
                failed = await conn.scalar(
                    text(
                        "SELECT count(*) FROM job WHERE status = 'failed' AND condominium_id = :c"
                    ),
                    {"c": condo_id},
                )
            if busy == 0:
                idle_since = idle_since or time.monotonic()
                if time.monotonic() - idle_since > 3:  # stays idle (no follow-up job appeared)
                    return int(failed or 0)
            else:
                idle_since = None
            await asyncio.sleep(1)
    finally:
        await engine.dispose()
    raise TimeoutError("a fila de jobs não esvaziou a tempo")


def bank_statement(truth: dict[str, Any]) -> bytes:
    """October statement: the condominium paid 8 of the 10 boletos on their due date."""
    boletos = sorted(
        (k, v["fields"]) for k, v in truth["documents"].items() if v["doc_type"] == "boleto"
    )
    trns = []
    for i, (_name, f) in enumerate(boletos[:8]):
        due = date.fromisoformat(f["vencimento"])
        amount = -Decimal(f["valor"])
        trns.append(
            f"<STMTTRN>\n<TRNTYPE>DEBIT\n<DTPOSTED>{due:%Y%m%d}120000[-3:BRT]\n"
            f"<TRNAMT>{amount}\n<FITID>PILOT{i:03d}\n<MEMO>PAG BOLETO {f['nome_beneficiario'][:30]}\n"
            "</STMTTRN>\n"
        )
    credit = date(2026, 10, 10)
    trns.append(
        f"<STMTTRN>\n<TRNTYPE>CREDIT\n<DTPOSTED>{credit:%Y%m%d}120000[-3:BRT]\n"
        f"<TRNAMT>62400.00\n<FITID>PILOTCRED\n<MEMO>TAXAS CONDOMINIAIS\n</STMTTRN>\n"
    )
    body = (
        "OFXHEADER:100\nDATA:OFXSGML\nVERSION:102\nSECURITY:NONE\nENCODING:USASCII\n"
        "CHARSET:1252\nCOMPRESSION:NONE\nOLDFILEUID:NONE\nNEWFILEUID:NONE\n\n"
        "<OFX>\n<BANKMSGSRSV1>\n<STMTTRNRS>\n<STMTRS>\n<CURDEF>BRL\n<BANKACCTFROM>\n"
        "<BANKID>0341\n<ACCTID>54321-0\n</BANKACCTFROM>\n<BANKTRANLIST>\n"
        + "".join(trns)
        + "</BANKTRANLIST>\n</STMTRS>\n</STMTTRNRS>\n</BANKMSGSRSV1>\n</OFX>\n"
    )
    return body.encode("cp1252")


async def upload(
    client: httpx.AsyncClient, condo: str, files: list[tuple[str, bytes]]
) -> dict[str, str]:
    r = await client.post(
        f"/condominiums/{condo}/documents",
        files=[("files", (name, data)) for name, data in files],
    )
    r.raise_for_status()
    out = {}
    for item in r.json():
        if item.get("error"):
            raise RuntimeError(f"upload recusado: {item['filename']}: {item['error']}")
        out[item["filename"]] = item["document_id"]
    return out


async def correct_queue(
    client: httpx.AsyncClient, condo: str, names: dict[str, str], truth: dict[str, Any]
) -> tuple[int, int]:
    """The analyst works the queue of this condominium. Returns (corrected, resolved)."""
    by_id = {v: k for k, v in names.items()}
    corrected = resolved = 0
    queue = [i for i in (await client.get("/queue")).json() if i["condominium_id"] == condo]
    for item in queue:
        if item["kind"] == "extracao":
            name = by_id.get(item["id"])
            if name is None or name not in truth["documents"]:
                raise RuntimeError(f"documento na fila sem gabarito: {item['title']}")
            gt = truth["documents"][name]
            r = await client.put(
                f"/condominiums/{condo}/documents/{item['id']}/review",
                json={"doc_type": gt["doc_type"], "values": gt["fields"]},
            )
            if r.status_code != 200:
                raise RuntimeError(f"correção recusada para {name}: {r.text}")
            corrected += 1
        elif item["kind"] == "casamento":
            issue = (await client.get(f"/condominiums/{condo}/match-issues/{item['id']}")).json()
            # A person would compare the options; the pilot takes the first and records it.
            choice = issue["candidates"][0]["id"] if issue["candidates"] else None
            r = await client.post(
                f"/condominiums/{condo}/match-issues/{item['id']}/resolve",
                json={"candidate_id": choice},
            )
            r.raise_for_status()
            resolved += 1
    return corrected, resolved


async def main(api: str, mailpit: str, admin_url: str, corpus: Path) -> int:
    truth = json.loads((corpus / "ground_truth.json").read_text(encoding="utf-8"))
    run = Run()
    condo = await onboard(admin_url)
    run.step("1. Condomínio cadastrado", condo)

    analyst = await login(api, mailpit, ANALYST)
    contract_name = "20_contrato.pdf"
    names = await upload(analyst, condo, [(contract_name, (corpus / contract_name).read_bytes())])
    await wait_idle(admin_url, condo)
    c, _ = await correct_queue(analyst, condo, names, truth)
    await wait_idle(admin_url, condo)
    contracts = (await analyst.get(f"/condominiums/{condo}/contracts")).json()
    run.step("2. Contrato enviado e registrado", f"{len(contracts)} contrato(s), {c} correção(ões)")

    others = sorted(p for p in truth["documents"] if p != contract_name)
    names |= await upload(analyst, condo, [(n, (corpus / n).read_bytes()) for n in others])
    names |= await upload(analyst, condo, [("extrato-2026-10.ofx", bank_statement(truth))])
    run.step("3. 29 documentos e o extrato de outubro enviados")
    failed = await wait_idle(admin_url, condo)
    run.step("4. Extração, casamento e regras concluídos", f"{failed} job(s) com falha")

    queue_before = [i for i in (await analyst.get("/queue")).json() if i["condominium_id"] == condo]
    extraction_queue = sum(i["kind"] == "extracao" for i in queue_before)
    total_corrected = c
    total_resolved = 0
    for _ in range(5):  # corrections create expenses, which may open new matches
        c, resolved_now = await correct_queue(analyst, condo, names, truth)
        total_corrected += c
        total_resolved += resolved_now
        await wait_idle(admin_url, condo)
        if c == 0 and resolved_now == 0:
            break
    run.step(
        "5. Fila de exceções tratada pela analista",
        f"{total_corrected} documento(s) corrigido(s), {total_resolved} casamento(s) resolvido(s)",
    )

    manager = await login(api, mailpit, MANAGER)
    serious = [
        f
        for f in (
            await manager.get(f"/condominiums/{condo}/findings", params={"competence": MONTH})
        ).json()
        if f["status"] == "aguardando_validacao"
    ]
    for f in serious:
        r = await manager.post(
            f"/condominiums/{condo}/findings/{f['id']}/decisions", json={"action": "validar"}
        )
        r.raise_for_status()
    await wait_idle(admin_url, condo)
    run.step("6. Gerente validou os achados graves", f"{len(serious)} validado(s)")

    closing = (await manager.get(f"/condominiums/{condo}/competences/{MONTH}/closing")).json()
    r = await manager.post(f"/condominiums/{condo}/competences/{MONTH}/close")
    if r.status_code != 200:
        print(f"Fechamento recusado: {r.text} (pendências: {closing})", file=sys.stderr)
        return 1
    run.step("7. Competência 10/2026 fechada e relatório publicado")

    sindica = await login(api, mailpit, SINDICA)
    files = {}
    for ext in ("pdf", "xlsx"):
        resp = await sindica.get(f"/condominiums/{condo}/reports/{MONTH}.{ext}")
        resp.raise_for_status()
        path = PILOT / f"relatorio-bosque-dos-ipes-{MONTH}.{ext}"
        path.write_bytes(resp.content)
        files[ext] = path
    findings = (
        await sindica.get(f"/condominiums/{condo}/findings", params={"competence": MONTH})
    ).json()
    summary = (
        await sindica.get(f"/condominiums/{condo}/summary", params={"competence": MONTH})
    ).json()
    run.step("8. Síndica baixou o relatório", f"{len(findings)} achado(s) no relatório")

    for client in (analyst, manager, sindica):
        await client.aclose()

    total = run.total
    ok = total < LIMIT_SECONDS
    automatic = 29 - extraction_queue  # the contract went first, outside this count
    by_rule: dict[str, int] = {}
    for f in findings:
        by_rule[f["rule_code"]] = by_rule.get(f["rule_code"], 0) + 1
    lines = [
        "# Execução do piloto — do upload ao relatório",
        "",
        f"Gerado por `make pilot` em {date.today():%d/%m/%Y}. Condomínio fictício "
        "**Bosque dos Ipês**, 30 documentos do corpus + extrato OFX de outubro/2026.",
        "",
        f"**Tempo total: {timedelta(seconds=round(total))}** (limite: 15 minutos) — "
        f"{'aceito' if ok else 'ACIMA DO LIMITE'}.",
        "",
        "| Etapa | Duração | Detalhe |",
        "|---|---|---|",
        *[f"| {name} | {secs:.1f} s | {detail} |" for name, secs, detail in run.steps],
        "",
        "## Resultado",
        "",
        f"- Documentos sem revisão manual: {automatic} de 29 (sem chave de API; ver "
        "`docs/extraction_accuracy.md`). Os demais foram corrigidos pela analista com o gabarito "
        "do corpus, pela mesma tela/API de correção.",
        f"- Achados no relatório: {len(findings)} "
        f"({', '.join(f'{k}: {v}' for k, v in sorted(by_rule.items())) or 'nenhum'}); "
        f"valor em risco: {brl(Decimal(summary['amount_at_risk']))}.",
        f"- Arquivos: `{files['pdf'].name}` e `{files['xlsx'].name}` nesta pasta.",
        "",
        "O tempo mede a execução do sistema (processamento, chamadas da interface e jobs); "
        "a leitura dos documentos pela analista é feita pelo script instantaneamente.",
    ]
    (PILOT / "run.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nTotal: {total:.0f} s — {'aceito' if ok else 'acima do limite'}; docs/pilot/run.md")
    return 0 if ok else 1


